interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  speechLang: string;
}

const I18nContext = createContext<I18n | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const id = setTimeout(() => {
      try {
        const saved = localStorage.getItem("preksha.lang") as Lang | null;
        if (saved && LANGS.some((l) => l.code === saved)) setLangState(saved);
      } catch {
        /* ignore */
      }
    }, 0);
    return () => clearTimeout(id);
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("preksha.lang", l);
    } catch {
      /* ignore */
    }
  };

  const t = (key: string) => DICT[lang][key] ?? DICT.en[key] ?? key;
  const speechLang = LANGS.find((l) => l.code === lang)?.speech ?? "en-IN";

  return <I18nContext.Provider value={{ lang, setLang, t, speechLang }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within a LanguageProvider");
  return ctx;
}
